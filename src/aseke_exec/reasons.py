# Outcomes that are "skipped" (policy gate, not a defect in the signal).
SKIP_CODES = frozenset(
    {R.ENTRIES_PAUSED, R.ACCOUNT_DISABLED, R.ACCOUNT_BLOCKED, R.ACCOUNT_NOT_RECONCILED,
     R.ACCOUNT_DEGRADED}
)


class Rejection(Exception):
    """A validated, explained refusal. ``code`` is machine readable."""

    def __init__(self, code: R, message: str, **details: Any):
        super().__init__(f"{code}: {message}")
        self.code = code
        self.message = message
        self.details = details

    def to_dict(self) -> dict[str, Any]:
        return {"code": str(self.code), "message": self.message, "details": self.details}
